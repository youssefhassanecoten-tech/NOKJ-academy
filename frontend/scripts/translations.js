      let currentLang = localStorage.getItem('nokj-language') || 'en';
      const originalTextMap = new WeakMap();

      function applyTranslation(lang) {
        const walker = document.createTreeWalker(
          document.body,
          NodeFilter.SHOW_TEXT, {
            acceptNode: function(node) {
              const parent = node.parentElement;
              if (!parent) return NodeFilter.FILTER_REJECT;
              const tag = parent.tagName;
              if (tag === 'SCRIPT' || tag === 'STYLE') return NodeFilter.FILTER_REJECT;
              if (node.nodeValue.trim() === '') return NodeFilter.FILTER_REJECT;
              return NodeFilter.FILTER_ACCEPT;
            }
          }
        );

        let nodes = [];
        let node;
        while (node = walker.nextNode()) {
          nodes.push(node);
        }

        nodes.forEach(function(textNode) {
          if (!originalTextMap.has(textNode)) {
            originalTextMap.set(textNode, textNode.nodeValue);
          }
          const original = originalTextMap.get(textNode);
          const trimmed = original.trim();
          if (lang === 'ru' && translations[trimmed] !== undefined) {
            textNode.nodeValue = original.replace(trimmed, translations[trimmed]);
          } else if (lang === 'en') {
            textNode.nodeValue = original;
          }
        });

        document.querySelectorAll('[placeholder]').forEach(function(el) {
          const placeholder = el.placeholder;
          if (lang === 'ru' && translations[placeholder] !== undefined) {
            el.placeholder = translations[placeholder];
          }
        });
      }

      function setLanguage(lang) {
        currentLang = lang;
        localStorage.setItem('nokj-language', lang);

        const ukFlags = document.querySelectorAll('#flag-uk, #login-flag-uk, #register-flag-uk');
        const ruFlags = document.querySelectorAll('#flag-ru, #login-flag-ru, #register-flag-ru');

        if (lang === 'en') {
          ukFlags.forEach(el => el.style.display = 'block');
          ruFlags.forEach(el => el.style.display = 'none');
        } else {
          ukFlags.forEach(el => el.style.display = 'none');
          ruFlags.forEach(el => el.style.display = 'block');
        }

        applyTranslation(lang);
        document.documentElement.lang = lang;
      }

      function toggleLanguage() {
        setLanguage(currentLang === 'en' ? 'ru' : 'en');
      }
